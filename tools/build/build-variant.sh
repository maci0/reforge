#!/usr/bin/env bash
# =============================================================================
# build-variant.sh — build a Buildroot rootfs with a variant defconfig fragment
# applied on top of br-external/configs/reforge_defconfig.
#
# Each variant gets its own build/output-<variant>/ output dir so the baseline
# build tree is untouched and side-by-side A/B is straightforward.
#
# Usage:
#   tools/build/build-variant.sh <variant-name> <fragment-file>
#
# Example (gcc15 phase-2 iter 7):
#   tools/build/build-variant.sh gcc15-base experiments/2026-06-04-toolchain-memory/gcc15-base.fragment
#
# Output:
#   build/output-<variant>/images/rootfs.tar
#
# Logs the full build to build/output-<variant>.log so background runs are
# inspectable.
# =============================================================================
set -euo pipefail

source "$(dirname "$0")/env.sh"

VARIANT="${1:?usage: build-variant.sh <variant> <fragment>}"
FRAGMENT="${2:?usage: build-variant.sh <variant> <fragment>}"

[ -f "${FRAGMENT}" ] || { echo "[build-variant] missing fragment: ${FRAGMENT}" >&2; exit 1; }

VARIANT_OUT="${REFORGE_ROOT}/build/output-${VARIANT}"
VARIANT_LOG="${REFORGE_ROOT}/build/output-${VARIANT}.log"
VARIANT_DEFCONFIG_DIR="${REFORGE_ROOT}/build/variant-configs"
VARIANT_DEFCONFIG="${VARIANT_DEFCONFIG_DIR}/reforge_${VARIANT}_defconfig"

mkdir -p "${VARIANT_DEFCONFIG_DIR}"

# Concatenate baseline defconfig + fragment.  Buildroot reads the named
# defconfig from BR2_EXTERNAL/configs/, so we copy our merged config into the
# br-external configs dir under a variant-specific name.
BASE_DEFCONFIG="${BR2_EXTERNAL_DIR}/configs/reforge_defconfig"
[ -f "${BASE_DEFCONFIG}" ] || { echo "[build-variant] missing base defconfig: ${BASE_DEFCONFIG}" >&2; exit 1; }

# Write a temp combined defconfig directly into br-external/configs/ so Buildroot
# can find it.  Tagged so we can clean it up later.
COMBINED="${BR2_EXTERNAL_DIR}/configs/reforge_${VARIANT}_defconfig"
{
    echo "# AUTOGENERATED by tools/build/build-variant.sh — variant=${VARIANT}"
    echo "# baseline: ${BASE_DEFCONFIG}"
    echo "# fragment: ${FRAGMENT}"
    echo "# Do not edit by hand; regenerate from the fragment."
    cat "${BASE_DEFCONFIG}"
    echo ""
    echo "# ---- fragment: ${FRAGMENT} ----"
    cat "${FRAGMENT}"
} > "${COMBINED}"

echo "[build-variant] variant=${VARIANT}" | tee "${VARIANT_LOG}"
echo "[build-variant] fragment=${FRAGMENT}" | tee -a "${VARIANT_LOG}"
echo "[build-variant] combined defconfig: ${COMBINED}" | tee -a "${VARIANT_LOG}"
echo "[build-variant] output dir: ${VARIANT_OUT}" | tee -a "${VARIANT_LOG}"
echo "[build-variant] build log:   ${VARIANT_LOG}" | tee -a "${VARIANT_LOG}"
echo "[build-variant] starting $(date -Is)" | tee -a "${VARIANT_LOG}"

br() { make -C "${BUILDROOT_GIT}" BR2_EXTERNAL="${BR2_EXTERNAL_DIR}" O="${VARIANT_OUT}" "$@"; }

br "reforge_${VARIANT}_defconfig" 2>&1 | tee -a "${VARIANT_LOG}"
br ${MULTICORE}                   2>&1 | tee -a "${VARIANT_LOG}"

echo "[build-variant] finished $(date -Is)" | tee -a "${VARIANT_LOG}"
echo "[build-variant] rootfs: ${VARIANT_OUT}/images/rootfs.tar" | tee -a "${VARIANT_LOG}"
